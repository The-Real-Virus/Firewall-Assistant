def engine_command() -> tuple[str, list[str]]:
    if getattr(sys, "frozen", False):
        engine = Path(sys.executable).resolve().with_name("wfdiag.exe")
        prefix: list[str] = []
    else:
        engine = (
            Path(sys.executable)
            .resolve()
            .with_name("python.exe" if sys.platform == "win32" else Path(sys.executable).name)
        )
        prefix = ["-I", "-m", "wfdiag"]
    check_plain_path(engine)
    if not engine.is_file():
        raise ValueError("Sibling engine is unavailable")
    return str(engine), prefix


def validate_result(request: DesktopRequest, terminal: DesktopEvent, code: int) -> object:
    if (
        terminal.type != "completed"
        or terminal.payload.exit_code != code
        or terminal.payload.output != request.parameters.out
    ):
        raise ValueError("Worker completion disagrees with process/output")
    output = Path(request.parameters.out)
    if (
        request.operation not in ("analyze", "collect")
        and terminal.payload.completeness != Completeness.COMPLETE
    ):
        raise ValueError("This operation cannot return incomplete completion")
    if request.operation == "analyze":
        loaded = read_gui_analysis(output)
        result = loaded.metadata if isinstance(loaded, AnalysisIndex) else loaded
        if (
            result.completeness != terminal.payload.completeness
            or result.engine_version != __version__
        ):
            if isinstance(loaded, AnalysisIndex):
                loaded.close()
            raise ValueError("Analysis state/version disagrees with completion")
        return loaded
    if request.operation == "collect":
        with VerifiedBundle(output) as bundle:
            for _ in bundle.iter_events():
                pass
            if (
                bundle.manifest.completeness != terminal.payload.completeness
                or bundle.manifest.collector_version != __version__
            ):
                raise ValueError("Capture state disagrees with completion")
            return bundle.manifest
    if request.operation == "doctor":
        report = read_record(output, DoctorReport, byte_limit=1024 * 1024)
        if report.engine_version != __version__:
            raise ValueError("Preflight output version differs")
        return report
    if request.operation == "propose":
        proposal = read_record(output, Proposal, byte_limit=1024 * 1024)
        if proposal.finding_id != request.parameters.finding_id:
            raise ValueError("Proposal finding differs from the request")
        return proposal
    if request.operation == "compare":
        return read_record(output, Comparison, byte_limit=MAX_ANALYSIS_BYTES)
    if output.suffix.lower() == ".json":
        if request.parameters.mode == "share":
            try:
                return read_record(output, ShareReport, byte_limit=MAX_INLINE_REPORT_BYTES)
            except RecordByteBudgetExceeded:
                validate_share_report(output)
                return output
        loaded = read_gui_analysis(output)
        if isinstance(loaded, AnalysisIndex):
            loaded.close()
        return output
    check_plain_path(output)
    # HTML is generated by the verified service template. Read it as data; do not open it.
    held = OpenedDirectory(output.parent)
    try:
        with held.open_relative(output.name) as stream:
            before = os.fstat(stream.fileno())
            if before.st_size > MAX_HTML_REPORT_BYTES:
                raise ValueError("HTML output exceeds its byte budget")
            count = 0
            prefix = bytearray()
            while chunk := stream.read(65536):
                count += len(chunk)
                if count > MAX_HTML_REPORT_BYTES:
                    raise ValueError("Actual HTML bytes exceed the budget")
                if len(prefix) < 4096:
                    prefix.extend(chunk[: 4096 - len(prefix)])
            after = os.fstat(stream.fileno())
            if (
                before.st_dev,
                before.st_ino,
                before.st_size,
                before.st_mtime_ns,
                before.st_ctime_ns,
            ) != (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns):
                raise ValueError("Opened HTML output changed")
    finally:
        held.close()
    if not prefix.startswith(b"<!doctype html>") or b"default-src 'none'" not in prefix:
        raise ValueError("Static HTML output is missing or invalid")
    return output


class CheckOutput(QRunnable):
    def __init__(
        self, owner: "DesktopJobs", request: DesktopRequest, terminal: DesktopEvent, code: int
    ) -> None:
        super().__init__()
        self.owner, self.request, self.terminal, self.code = owner, request, terminal, code

    def run(self) -> None:
        try:
            result = validate_result(self.request, self.terminal, self.code)
        except (OSError, ValueError, DiagnosticError):
            self.owner.checked.emit(self.request.job_id, None, "INVALID_OUTPUT")
        else:
            self.owner.checked.emit(self.request.job_id, result, "")


class DesktopJobs(QObject):
    progress = Signal(str)
    completed = Signal(object, object)
    failed = Signal(str, int)
    cancelled = Signal(bool)
    busyChanged = Signal(bool)
    checked = Signal(str, object, str)

    def __init__(self, job_root: Path, parent: QObject | None = None) -> None:
        super().__init__(parent if parent is not None else QCoreApplication.instance())
        self.job_root = job_root
        self.request: DesktopRequest | None = None
        self.process: QProcess | None = None
        self.decoder: EventDecoder | None = None
        self.terminal: DesktopEvent | None = None
        self.stderr = bytearray()
        self.stderr_truncated = False
        self.cancel_requested = False
        self.protocol_error = False
        self._held_directory: WindowsDirectory | None = None
        self.pool = QThreadPool(self)
        self.pool.setMaxThreadCount(1)
        self.checked.connect(self._checked)
        self.deadline = QTimer(self)
        self.deadline.setSingleShot(True)
        self.deadline.timeout.connect(self.cancel)
        self.kill_timer = QTimer(self)
        self.kill_timer.setSingleShot(True)
        self.kill_timer.timeout.connect(self._kill)

    @property
    def busy(self) -> bool:
        return self.request is not None

    def clear_log_buffer(self) -> None:
        if self.busy:
            raise ValueError("Wait for the active job before clearing its bounded log buffer")
        self.stderr.clear()
        self.stderr_truncated = False

    def start(self, request: DesktopRequest) -> None:
        if self.busy:
            raise ValueError("Only one diagnostic job can run at a time")
        executable, prefix = engine_command()
        directory = self.job_root / request.job_id
        self._held_directory = create_private_directory(directory)
        try:
            payload = request.model_dump_json().encode("utf-8")
            write_new_bytes(directory / "request.json", payload, byte_limit=64 * 1024)
        except BaseException:
            self._release_directory()
            raise
        self.request = request
        self.decoder = EventDecoder(request.job_id)
        self.terminal = None
        self.stderr.clear()
        self.stderr_truncated = False
        self.cancel_requested = False
        self.protocol_error = False
        process = QProcess(self)
        self.process = process
        process.setWorkingDirectory(str(directory))
        environment = QProcessEnvironment()
        for name in (
            "SystemRoot",
            "WINDIR",
            "TEMP",
            "TMP",
            "USERPROFILE",
            "LOCALAPPDATA",
            "APPDATA",
            "LANG",
            "LC_ALL",
        ):
            value = os.environ.get(name)
            if value is not None:
                environment.insert(name, value)
        process.setProcessEnvironment(environment)
        process.readyReadStandardOutput.connect(lambda p=process: self._stdout(p))
        process.readyReadStandardError.connect(lambda p=process: self._stderr(p))
        process.finished.connect(lambda code, status, p=process: self._finished(p, code, status))
        process.errorOccurred.connect(lambda error, p=process: self._error(p, error))
        self.busyChanged.emit(True)
        self.deadline.start((DEADLINES[request.operation] + 10) * 1000)
        process.start(
            executable, [*prefix, "desktop-job", "--request", str(directory / "request.json")]
        )

    def _stdout(self, process: QProcess) -> None:
        if process is not self.process or self.decoder is None:
            return
        data = bytes(process.readAllStandardOutput().data())
        try:
            events = self.decoder.feed(data)
            for event in events:
                if event.type == "started" and event.payload.engine_version != __version__:
                    raise ValueError("Wrong worker engine version")
                if event.type == "progress":
                    self.progress.emit(event.payload.stage)
                if event.type in ("completed", "failed", "cancelled"):
                    self.terminal = event
        except ValueError:
            self.protocol_error = True
            self.cancel()

    def _stderr(self, process: QProcess) -> None:
        if process is not self.process:
            return
        data = bytes(process.readAllStandardError().data())
        remaining = MAX_STDERR_BYTES - len(self.stderr)
        self.stderr.extend(data[: max(0, remaining)])
        self.stderr_truncated |= len(data) > remaining

    def cancel(self) -> None:
        if self.request is None or self.cancel_requested:
            return
        self.cancel_requested = True
        if self.process is not None and self.process.state() != QProcess.ProcessState.NotRunning:
            control = CancelControl(job_id=self.request.job_id, type="cancel")
            self.process.write((control.model_dump_json() + "\n").encode())
            self.process.closeWriteChannel()
            self.kill_timer.start(8000)

    def _kill(self) -> None:
        if self.process is not None and self.process.state() != QProcess.ProcessState.NotRunning:
            self.process.kill()

    def _error(self, process: QProcess, error: QProcess.ProcessError) -> None:
        if process is self.process and error == QProcess.ProcessError.FailedToStart:
            self._reset()
            self.failed.emit("ENGINE_START_FAILED", 6)

    def _finished(self, process: QProcess, code: int, status: QProcess.ExitStatus) -> None:
        if process is not self.process or self.request is None:
            return
        self._stdout(process)
        self._stderr(process)
        self.deadline.stop()
        self.kill_timer.stop()
        try:
            if self.decoder is None:
                raise ValueError("No decoder")
            self.decoder.finish()
            if (
                self.protocol_error
                or status != QProcess.ExitStatus.NormalExit
                or self.terminal is None
            ):
                raise ValueError("Invalid process completion")
        except ValueError:
            self._reset()
            self.failed.emit("WORKER_PROTOCOL_OR_PROCESS_FAILED", 6)
            return
        terminal = self.terminal
        if self.cancel_requested or terminal.type == "cancelled":
            confirmed = (
                terminal.type == "cancelled" and terminal.payload.cleanup_confirmed and code == 5
            )
            self._reset()
            self.cancelled.emit(confirmed)
        elif terminal.type == "failed":
            reason = terminal.payload.code
            actual = terminal.payload.exit_code if terminal.payload.exit_code == code else 6
            self._reset()
            self.failed.emit(reason, actual)
        else:
            self.pool.start(CheckOutput(self, self.request, terminal, code))

    @Slot(str, object, str)
    def _checked(self, job_id: str, result: object, error: str) -> None:
        if self.request is None or self.request.job_id != job_id:
            if isinstance(result, AnalysisIndex):
                result.close()
            return
        request = self.request
        cancelled = self.cancel_requested
        self._reset()
        if cancelled:
            if isinstance(result, AnalysisIndex):
                result.close()
            self.cancelled.emit(False)
        elif error:
            self.failed.emit(error, 6)
        else:
            self.completed.emit(request, result)

    def _release_directory(self) -> None:
        if self._held_directory is not None:
            self._held_directory.close()
            self._held_directory = None

    def _reset(self) -> None:
        self.deadline.stop()
        self.kill_timer.stop()
        self._release_directory()
        if self.process is not None:
            self.process.deleteLater()
        self.process = None
        self.request = None
        self.decoder = None
        self.terminal = None
        self.busyChanged.emit(False)
